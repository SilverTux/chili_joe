  const languageButtons = document.querySelectorAll("[data-language]");
  const attributeBindings = [
    ["data-i18n-alt", "alt"],
    ["data-i18n-aria-label", "aria-label"],
    ["data-i18n-title", "title"]
  ];

  function applyLanguage(language) {
    const selectedLanguage = translations[language] ? language : "en";
    const messages = translations[selectedLanguage];

    document.documentElement.lang = selectedLanguage;
    document.title = messages.pageTitle;

    document.querySelectorAll("[data-i18n]").forEach((element) => {
      const message = messages[element.dataset.i18n];
      if (message !== undefined) element.textContent = message;
    });

    document.querySelectorAll("[data-i18n-html]").forEach((element) => {
      const message = messages[element.dataset.i18nHtml];
      if (message !== undefined) element.innerHTML = message;
    });

    attributeBindings.forEach(([dataAttribute, attribute]) => {
      document.querySelectorAll(`[${dataAttribute}]`).forEach((element) => {
        const key = element.getAttribute(dataAttribute);
        if (messages[key] !== undefined) element.setAttribute(attribute, messages[key]);
      });
    });

    document.querySelectorAll("[data-i18n-meta]").forEach((element) => {
      const message = messages[element.dataset.i18nMeta];
      if (message !== undefined) element.setAttribute("content", message);
    });

    languageButtons.forEach((button) => {
      button.setAttribute("aria-pressed", String(button.dataset.language === selectedLanguage));
    });

    try {
      localStorage.setItem("chili-joes-language", selectedLanguage);
    } catch {
      // The language switch still works when browser storage is unavailable.
    }
  }

  let savedLanguage = "en";
  try {
    savedLanguage = localStorage.getItem("chili-joes-language") || "en";
  } catch {
    // Use English by default when browser storage is unavailable.
  }

  languageButtons.forEach((button) => {
    button.addEventListener("click", () => applyLanguage(button.dataset.language));
  });
  applyLanguage(savedLanguage);
